create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text, credits integer not null default 10, plan text not null default 'free',
  plan_expires_at timestamptz, created_at timestamptz not null default now()
);

create table if not exists public.lookups (
  id bigint generated by default as identity primary key, user_id uuid not null references auth.users(id) on delete cascade,
  lookup_type text not null check (lookup_type in ('number', 'aadhar')), query_hash text not null, created_at timestamptz not null default now()
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key, user_id uuid not null references auth.users(id) on delete cascade,
  plan_days integer not null check (plan_days in (1,7,30)), amount integer not null check (amount in (30,100,300)),
  receipt_name text, receipt_path text, status text not null default 'pending' check (status in ('pending','approved','rejected')),
  reviewed_at timestamptz, reviewed_by text, created_at timestamptz not null default now()
);

alter table public.payments add column if not exists receipt_path text;
alter table public.payments add column if not exists reviewed_at timestamptz;
alter table public.payments add column if not exists reviewed_by text;

create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$
begin insert into public.profiles(id,email,credits) values(new.id,new.email,10) on conflict(id) do nothing; return new; end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.lookups enable row level security;
alter table public.payments enable row level security;
