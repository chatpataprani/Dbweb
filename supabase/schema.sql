create or replace function public.approve_payment(p_payment_id bigint,p_admin_email text) returns public.payments
language plpgsql security definer set search_path=public as $$
declare v_payment public.payments; v_profile public.profiles; v_expiry timestamptz;
begin
  if lower(coalesce(p_admin_email,'')) <> lower('lumenomore@hotmail.com') then raise exception 'Not authorized'; end if;
  select * into v_payment from public.payments where id=p_payment_id for update;
  if not found then raise exception 'Payment not found'; end if;
  if v_payment.status <> 'pending' then raise exception 'Payment is already reviewed'; end if;
  select * into v_profile from public.profiles where id=v_payment.user_id for update;
  if not found then raise exception 'User profile not found'; end if;
  v_expiry := greatest(coalesce(v_profile.plan_expires_at,now()),now()) + make_interval(days=>v_payment.plan_days);
  update public.profiles set plan=v_payment.plan_days || 'd', plan_expires_at=v_expiry, credits=v_profile.credits+10 where id=v_payment.user_id;
  update public.payments set status='approved',reviewed_at=now(),reviewed_by=p_admin_email where id=p_payment_id returning * into v_payment;
  return v_payment;
end; $$;
revoke all on function public.approve_payment(bigint,text) from public;
revoke all on function public.approve_payment(bigint,text) from anon;
revoke all on function public.approve_payment(bigint,text) from authenticated;
grant execute on function public.approve_payment(bigint,text) to service_role;